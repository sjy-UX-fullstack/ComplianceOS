// ─── ref_no generation ─────────────────────────────────────────────────────
// Format: BR-YYYY-XXXXXX (per-year sequence, 6-digit). The sequence is
// generated by hashing the UUID for stable in-memory testing; a real DB
// deploy should use a Postgres sequence or `nextval()`.

export function buildRefNo(seq: number, year: number = new Date().getUTCFullYear()): string {
  return `BR-${year}-${seq.toString().padStart(6, "0")}`;
}

export function ephemeralRefNo(id: string): string {
  const seq = parseInt(crypto.createHash("sha1").update(id).digest("hex").slice(0, 6), 16) % 1_000_000;
  return buildRefNo(seq);
}

// ─── Dual-clock state ──────────────────────────────────────────────────────

export interface ClockState {
  due: Date;
  msRemaining: number;
  hoursRemaining: number;
  isOverdue: boolean;
  severity: "ok" | "warn" | "danger" | "overdue";
}

function clockSeverity(hours: number): ClockState["severity"] {
  if (hours < 0) return "overdue";
  if (hours <= 1) return "danger";
  if (hours <= 6) return "warn";
  return "ok";
}

export function computeClockState(due: Date, now: Date = new Date()): ClockState {
  const ms = due.getTime() - now.getTime();
  const hours = ms / (60 * 60 * 1000);
  return {
    due,
    msRemaining: Math.max(0, ms),
    hoursRemaining: Math.max(0, Math.round(hours * 10) / 10),
    isOverdue: ms < 0,
    severity: clockSeverity(hours),
  };
}

export function computeDeadlines(detectedAt: Date): {
  certInDueAt: Date;
  dpbDueAt: Date;
} {
  return {
    certInDueAt: new Date(detectedAt.getTime() + BREACH_TIMERS.CERT_IN_HOURS * 60 * 60 * 1000),
    dpbDueAt: new Date(detectedAt.getTime() + BREACH_TIMERS.DPB_HOURS * 60 * 60 * 1000),
  };
}


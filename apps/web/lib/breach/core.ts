// Linear progression; the wizard fans out simultaneously rather than strict order.
const TRANSITIONS: Record<BreachStatus, BreachStatus[]> = {
  open: ["investigating", "contained", "closed"],
  investigating: ["contained", "cert_in_filed", "dpb_initial_filed", "closed"],
  contained: ["cert_in_filed", "dpb_initial_filed", "principals_notified", "closed"],
  cert_in_filed: ["dpb_initial_filed", "principals_notified", "closed"],
  dpb_initial_filed: ["dpb_detailed_filed", "principals_notified", "closed"],
  dpb_detailed_filed: ["principals_notified", "closed"],
  principals_notified: ["closed"],
  closed: [],
};

export function canTransition(from: BreachStatus, to: BreachStatus): boolean {
  return TRANSITIONS[from]?.includes(to) ?? false;
}
